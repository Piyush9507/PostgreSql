	MONTHLY AS (
		SELECT
			DATE_TRUNC('month', ORDER_DATE) AS MONTHS,
			sum(net_total) as revenue
		FROM
			SALES.ORDERS
			group by DATE_TRUNC('month', ORDER_DATE)
	)
select *,
	(revenue -  lag(revenue) over(order by months))* 100.0 / lag(revenue) over(order by months) as mom_pct
from monthly
order by mom_pct desc

