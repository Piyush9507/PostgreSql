WITH
	STORE_REV AS (
		SELECT
			STORE_ID,
			SUM(NET_TOTAL) AS STORE_REV
		FROM
			SALES.ORDERS
		GROUP BY
			STORE_ID -- IMP
	)
SELECT
	*,
	DENSE_RANK() OVER (
		ORDER BY
			STORE_REV DESC
	) AS STORE_RANK,
	FIRST_VALUE(STORE_REV) OVER W AS TOP1,
	FIRST_VALUE(STORE_REV) OVER W - STORE_REV AS GAP_FROM_TOP1,
	NTH_VALUE(STORE_REV, 2) OVER W AS TOP2,
	NTH_VALUE(STORE_REV, 2) OVER W - STORE_REV AS GAP_FROM_TOP2,
	LAG(STORE_REV) OVER (
		ORDER BY
			STORE_REV DESC
	) AS PREV_STORE_REV
FROM
	STORE_REV
WINDOW
	W AS (
		ORDER BY
			STORE_REV DESC ROWS BETWEEN UNBOUNDED PRECEDING
			AND UNBOUNDED FOLLOWING
	)

