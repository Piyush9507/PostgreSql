WITH
	RANKED AS (
		SELECT
			*,
			NTH_VALUE(NET_TOTAL, 1) OVER W AS LARGEST_ORDER,
			NTH_VALUE(NET_TOTAL, 2) OVER W AS SECOND_LARGEST_ORDER
		FROM
			SALES.ORDERS
		WINDOW
			W AS (
				PARTITION BY
					STORE_ID
				ORDER BY
					NET_TOTAL DESC ROWS BETWEEN UNBOUNDED PRECEDING
					AND UNBOUNDED FOLLOWING
			)
	)
SELECT
	STORE_ID,
	LARGEST_ORDER,
	SECOND_LARGEST_ORDER,
	LARGEST_ORDER - SECOND_LARGEST_ORDER AS DIFF
FROM
	RANKED

