WITH
	ADD_DEPT_MATRIC AS (
		SELECT
			*,
			FIRST_VALUE(SALARY) OVER (
				PARTITION BY
					DEPT_ID
				ORDER BY
					SALARY DESC
			) AS DEPT_HIGHTES_SALARY,
			FIRST_VALUE(SALARY) OVER (
				PARTITION BY
					DEPT_ID
				ORDER BY
					SALARY ASC
			) AS DEPT_LOWEST_SALARY
		FROM
			STORES.EMPLOYEES
	)
SELECT
	*,
	ROUND(
		(
			(SALARY - DEPT_LOWEST_SALARY) * 100.0 / (DEPT_HIGHTES_SALARY - DEPT_LOWEST_SALARY)
		),
		2
	) AS PCT_OF_RANGE
FROM
	ADD_DEPT_MATRIC
	-- Perentile formula: ((value - min) / (max - min)) * 100.0

