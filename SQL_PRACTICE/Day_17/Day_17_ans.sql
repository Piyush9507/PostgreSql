WITH
	DIFF_CALC AS (
		SELECT
			*,
			LAG(CREATED_DATE) OVER (
				PARTITION BY
					AGENT_ID
				ORDER BY
					CREATED_DATE
			) AS PREV_CD,
			CREATED_DATE - LAG(CREATED_DATE) OVER (
				PARTITION BY
					AGENT_ID
				ORDER BY
					CREATED_DATE
			) AS DIFF
		FROM
			SUPPORT.TICKETS
	)
SELECT
	AGENT_ID,
	CREATED_DATE,
	PREV_CD,
	MIN(DIFF)
FROM
	DIFF_CALC
GROUP BY
	AGENT_ID,
	CREATED_DATE,
	PREV_CD
LIMIT
	1

