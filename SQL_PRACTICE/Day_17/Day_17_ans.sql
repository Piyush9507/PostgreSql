WITH
	BUDGET AS (
		SELECT
			*,
			FIRST_VALUE(BUDGET) OVER (
				ORDER BY
					START_DATE
			) AS FIRST_BUDGET,
			FIRST_VALUE(BUDGET) OVER (
				ORDER BY
					START_DATE DESC
			) AS LAST_BUDGET
		FROM
			MARKETING.CAMPAIGNS
	)
SELECT
	CAMPAIGN_ID,
	FIRST_BUDGET,
	LAST_BUDGET,
	CASE
		WHEN LAST_BUDGET > FIRST_BUDGET THEN 'Increasing'
		WHEN LAST_BUDGET < FIRST_BUDGET THEN 'Decreasing'
		ELSE 'FLAT'
	END AS TREND
FROM
	BUDGET

