WITH
	TICKETS AS (
		SELECT
			*,
			LAG(CREATED_DATE) OVER (
				PARTITION BY
					AGENT_ID
				ORDER BY
					CREATED_DATE
			) AS PREV_TICKET_TIME
		FROM
			SUPPORT.TICKETS
		WHERE
			RESOLVED_DATE IS NOT NULL
	),
	GAP AS (
		SELECT
			*,
			CREATED_DATE - PREV_TICKET_TIME AS TIME_BW_TWO_TICKETS
		FROM
			TICKETS
		WHERE
			PREV_TICKET_TIME IS NOT NULL
	)
SELECT
	AGENT_ID,
	AVG(TIME_BW_TWO_TICKETS) AS AVG_GAP
FROM
	GAP
GROUP BY
	AGENT_ID
ORDER BY
	AVG_GAP

