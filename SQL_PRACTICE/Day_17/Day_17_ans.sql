SELECT
	*,
	LAG(NET_TOTAL) OVER (
		PARTITION BY
			CUST_ID
		ORDER BY
			ORDER_DATE
	) AS PREV_NET_TOTAL,
	NET_TOTAL - LAG(NET_TOTAL) OVER (
		PARTITION BY
			CUST_ID
		ORDER BY
			ORDER_DATE
	) AS CHANGE
FROM
	SALES.ORDERS

