WITH
	PODIUM AS (
		SELECT
			*,
			FIRST_VALUE(SALARY) OVER (
				PARTITION BY
					DEPT_ID
				ORDER BY
					SALARY DESC
			) AS GOLD,
			NTH_VALUE(SALARY, 2) OVER (
				PARTITION BY
					DEPT_ID
				ORDER BY
					SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING
					AND UNBOUNDED FOLLOWING
			) AS SILVER,
			NTH_VALUE(SALARY, 2) OVER (
				PARTITION BY
					DEPT_ID
				ORDER BY
					SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING
					AND UNBOUNDED FOLLOWING
			) AS BRONZE
		FROM
			STORES.EMPLOYEES
	)
SELECT DISTINCT
	DEPT_ID,
	SALARY,
	GOLD,
	SILVER,
	BRONZE,
	GOLD - BRONZE AS DIFF
FROM
	PODIUM

