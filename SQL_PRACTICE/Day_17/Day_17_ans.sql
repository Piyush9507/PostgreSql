WITH
	REV_PER_STORE AS (
		SELECT
			STORE_ID,
			SUM(NET_TOTAL) AS TOTAL_REV
		FROM
			SALES.ORDERS
		GROUP BY
			STORE_ID
	),
	PODIUM AS (
		SELECT
			STORE_ID,
			TOTAL_REV,
			NTH_VALUE(TOTAL_REV, 1) OVER W AS FIRST,
			NTH_VALUE(TOTAL_REV, 2) OVER W AS SECOND,
			NTH_VALUE(TOTAL_REV, 3) OVER W AS THIRD
		FROM
			REV_PER_STORE
		WINDOW
			W AS (
				ORDER BY
					TOTAL_REV DESC ROWS BETWEEN UNBOUNDED PRECEDING
					AND UNBOUNDED FOLLOWING
			)
	)
SELECT
	*,
	FIRST - TOTAL_REV AS GAP
FROM
	PODIUM



