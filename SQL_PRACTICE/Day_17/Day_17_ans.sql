WITH
	WEEKLY AS (
		SELECT
			DATE_TRUNC('week', ORDER_DATE) AS WEEK,
			COUNT(*) AS ORDER_COUNT
		FROM
			SALES.ORDERS
		GROUP BY
			DATE_TRUNC('week', ORDER_DATE)
	)
SELECT
	*,
	LAG(ORDER_COUNT) OVER (
		ORDER BY
			ORDER_COUNT
	) AS PREV_ORD_CNT,
	ROUND(
		(
			ORDER_COUNT - LAG(ORDER_COUNT) OVER (
				ORDER BY
					ORDER_COUNT
			)
		) * 100.0 / NULLIF(
			LAG(ORDER_COUNT) OVER (
				ORDER BY
					ORDER_COUNT
			),
			0
		),
		2
	) AS WOW_GROWTH_PCT
FROM
	WEEKLY

