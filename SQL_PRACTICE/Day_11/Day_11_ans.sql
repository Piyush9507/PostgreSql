SELECT
	S.STORE_ID,
	S.STORE_NAME,
	MON.MONTH,
	COUNT(DISTINCT O.ORDER_ID) AS ORDER_COUNT
FROM
	STORES.STORES S
	CROSS JOIN (
		SELECT
			GENERATE_SERIES(1, 12, 1) AS MONTH
	) MON
	LEFT JOIN SALES.ORDERS O ON O.STORE_ID = S.STORE_ID
	AND EXTRACT(
		'month'
		FROM
			ORDER_DATE
	) = MON.MONTH
	AND EXTRACT(
		'year'
		FROM
			ORDER_DATE
	) = 2025
GROUP BY
	S.STORE_ID,
	S.STORE_NAME,
	MON.MONTH
ORDER BY
	S.STORE_ID,
	S.STORE_NAME,
	MON.MONTH

-- ANSWER 26
SELECT
	MAIN.MONTH,
	NEW_O.TOTAL_ORDERS + NEW_R.TOTAL_RETURNS AS TOTAL_ACTIVITY
FROM
	(
		SELECT
			EXTRACT(
				'month'
				FROM
					ORDER_DATE
			) AS MONTH
		FROM
			SALES.ORDERS
		WHERE
			EXTRACT(
				'year'
				FROM
					ORDER_DATE
			) = 2025
		GROUP BY
			EXTRACT(
				'month'
				FROM
					ORDER_DATE
			)
		HAVING
			COUNT(ORDER_ID) > 1000
		INTERSECT
		SELECT
			EXTRACT(
				'month'
				FROM
					RETURN_DATE
			) AS MONTH
		FROM
			SALES.RETURNS
		WHERE
			EXTRACT(
				'year'
				FROM
					RETURN_DATE
			) = 2025
		GROUP BY
			EXTRACT(
				'month'
				FROM
					RETURN_DATE
			)
		HAVING
			COUNT(RETURN_ID) > 50
	) MAIN
	LEFT JOIN (
		SELECT
			EXTRACT(
				'month'
				FROM
					ORDER_DATE
			) AS MONTH,
			COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS
		FROM
			SALES.ORDERS
		WHERE
			EXTRACT(
				'year'
				FROM
					ORDER_DATE
			) = 2025
		GROUP BY
			EXTRACT(
				'month'
				FROM
					ORDER_DATE
			)
	) NEW_O USING (MONTH)
	LEFT JOIN (
		SELECT
			EXTRACT(
				'month'
				FROM
					RETURN_DATE
			) AS MONTH,
			COUNT(DISTINCT RETURN_ID) AS TOTAL_RETURNS
		FROM
			SALES.RETURNS
		WHERE
			EXTRACT(
				'year'
				FROM
					RETURN_DATE
			) = 2025
		GROUP BY
			EXTRACT(
				'month'
				FROM
					RETURN_DATE
			)
	) NEW_R USING (MONTH)
ORDER BY
	TOTAL_ACTIVITY DESC
LIMIT
	1

