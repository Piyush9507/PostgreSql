	E1.STORE_ID,
	CASE
		WHEN E1.DEPT_ID = E2.DEPT_ID THEN 'Same Dept'
		WHEN E1.ROLE = E2.ROLE THEN 'Same Role'
		ELSE 'Cross-Functional'
	END
ORDER BY
	STORE_ID

-- ANSWER 31
SELECT
	D.DEPT_NAME,
	ALL_EMPLOYEES.*,
	DEPT_MAX_SAL_DIFF.MAX_SAL_DIFF
FROM
	(
		SELECT
			EMP1.DEPT_ID,
			EMP1.FIRST_NAME AS EMP1_NAME,
			EMP1.SALARY AS EM1_SALARY,
			EMP2.FIRST_NAME AS EMP2_NAME,
			EMP2.SALARY AS EM2_SALARY,
			ABS(EMP1.SALARY - EMP2.SALARY) AS SALARY_DIFFERENCE
		FROM
			STORES.EMPLOYEES EMP1
			JOIN STORES.EMPLOYEES EMP2 ON EMP1.DEPT_ID = EMP2.DEPT_ID
			AND EMP1.EMPLOYEE_ID < EMP2.EMPLOYEE_ID
	) ALL_EMPLOYEES
	JOIN (
		SELECT
			E1.DEPT_ID,
			MAX(ABS(E1.SALARY - E2.SALARY)) AS MAX_SAL_DIFF
		FROM
			STORES.EMPLOYEES E1
			JOIN STORES.EMPLOYEES E2 ON E1.DEPT_ID = E2.DEPT_ID
			AND E1.EMPLOYEE_ID < E2.EMPLOYEE_ID
		GROUP BY
			E1.DEPT_ID
		ORDER BY
			DEPT_ID
	) DEPT_MAX_SAL_DIFF ON ALL_EMPLOYEES.DEPT_ID = DEPT_MAX_SAL_DIFF.DEPT_ID
	AND ALL_EMPLOYEES.SALARY_DIFFERENCE = DEPT_MAX_SAL_DIFF.MAX_SAL_DIFF
	LEFT JOIN CORE.DIM_DEPARTMENT D ON DEPT_MAX_SAL_DIFF.DEPT_ID = D.DEPT_ID
ORDER BY
	DEPT_MAX_SAL_DIFF.DEPT_ID

