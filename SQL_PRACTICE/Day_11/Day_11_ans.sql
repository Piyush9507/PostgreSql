SELECT
	C.CATEGORY_ID,
	C.CATEGORY_NAME,
	M.MONTH,
	COUNT(ORD.ORDER_ITEM_ID) AS TOTAL_ITEMS_SOLD
FROM
	CORE.DIM_CATEGORY C
	CROSS JOIN (
		SELECT
			GENERATE_SERIES(1, 12, 1) AS MONTH
	) M
	LEFT JOIN (
		SELECT
			OI.ORDER_ITEM_ID,
			O.ORDER_DATE,
			B.CATEGORY_ID
		FROM
			SALES.ORDER_ITEMS OI
			JOIN SALES.ORDERS O USING (ORDER_ID)
			JOIN PRODUCTS.PRODUCTS P ON OI.PROD_ID = P.PRODUCT_ID
			JOIN CORE.DIM_BRAND B USING (BRAND_ID)
	) ORD ON C.CATEGORY_ID = ORD.CATEGORY_ID
	AND EXTRACT(
		'month'
		FROM
			ORD.ORDER_DATE
	) = M.MONTH
GROUP BY
	C.CATEGORY_ID,
	C.CATEGORY_NAME,
	M.MONTH
ORDER BY
	C.CATEGORY_ID

