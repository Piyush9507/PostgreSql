SELECT
	E1.STORE_ID,
	CASE
		WHEN E1.DEPT_ID = E2.DEPT_ID THEN 'Same Dept'
		WHEN E1.ROLE = E2.ROLE THEN 'Same Role'
		ELSE 'Cross-Functional'
	END AS CLASSIFICATION,
	COUNT(*) AS PAIR_COUNT
