SELECT
	CASE
		WHEN E.EMPLOYEE_ID IS NOT NULL
		AND T.AGENT_ID IS NOT NULL THEN 'ACTIVE AGENT'
		WHEN E.EMPLOYEE_ID IS NOT NULL
		AND T.AGENT_ID IS NULL THEN 'EMPLOYEE - NO TICKETS'
		WHEN E.EMPLOYEE_ID IS NULL
		AND T.AGENT_ID IS NOT NULL THEN 'TICKET - INVALID AGENT'
	END AS CATEGORY,
	COUNT(*) AS COUNT
FROM
	STORES.EMPLOYEES E
	FULL JOIN SUPPORT.TICKETS T ON E.EMPLOYEE_ID = T.AGENT_ID
GROUP BY
	CASE
		WHEN E.EMPLOYEE_ID IS NOT NULL
		AND T.AGENT_ID IS NOT NULL THEN 'ACTIVE AGENT'
		WHEN E.EMPLOYEE_ID IS NOT NULL
		AND T.AGENT_ID IS NULL THEN 'EMPLOYEE - NO TICKETS'
		WHEN E.EMPLOYEE_ID IS NULL
		AND T.AGENT_ID IS NOT NULL THEN 'TICKET - INVALID AGENT'
	END
ORDER BY CATEGORY

