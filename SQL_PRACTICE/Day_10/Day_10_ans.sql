		ELSE 'ORPHAN CUSTOMER'
	END AS STATUS,
	COUNT(*)
FROM
	CUSTOMERS.CUSTOMERS C
	FULL JOIN SALES.ORDERS O ON O.CUST_ID = C.CUSTOMER_ID
GROUP BY
	CASE
		WHEN O.CUST_ID IS NOT NULL
		AND C.CUSTOMER_ID IS NOT NULL THEN 'Good Records'
		WHEN C.CUSTOMER_ID IS NULL THEN 'Orphan Order'
		ELSE 'ORPHAN CUSTOMER'
	END

