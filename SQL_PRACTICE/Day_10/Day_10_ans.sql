		WHEN O.ORDER_ID IS NULL THEN 'Orphan Shipment'
		ELSE 'Delivered/Shipped/Returned'
	END AS STATUS,
	COUNT(*)
FROM
	SALES.ORDERS O
	FULL JOIN SALES.SHIPMENTS S ON S.ORDER_ID = O.ORDER_ID
GROUP BY
	CASE
		WHEN S.ORDER_ID IS NULL THEN 'Not Shipped'
		WHEN O.ORDER_ID IS NULL THEN 'Orphan Shipment'
		ELSE 'Delivered/Shipped/Returned'
	END

